// Writes lib/panel-models.js: modelun's runnable consensus-panel models, plus the OpenRouter id
// of every hand-written model OpenRouter also serves (its fallback route). Re-run when modelun's
// roster changes:
//   node scripts/sync-panel.mjs [path/to/modelun]
import { readFileSync, writeFileSync } from 'node:fs';
import { handWrittenModels, labOf, CHARS_PER_TOKEN } from '../lib/llm.js';

const MODELUN = process.argv[2] || `${process.env.HOME}/dev/convovo/modelun`;
const SPEC = `${MODELUN}/studies/consensus/spec`;
const OUT = new URL('../lib/panel-models.js', import.meta.url);

// Hand-written models whose OpenRouter id is neither their key nor their modelName
const ALIASES = {
  'llama-3.3-70b': 'meta-llama/llama-3.3-70b-instruct',
  'qwen3-235b-a22b': 'qwen/qwen3-235b-a22b-2507',
  'qwen2.5-72b': 'qwen/qwen-2.5-72b-instruct',
  'mistral-small-3.2': 'mistralai/mistral-small-3.2-24b-instruct',
  'muse-wonder-1.0': 'meta/muse-wonder',
};

const roster = readFileSync(`${SPEC}/models.txt`, 'utf8').split('\n').map(s => s.trim()).filter(Boolean);
const { models, unrunnable } = JSON.parse(readFileSync(`${SPEC}/models.json`, 'utf8'));
const meta = new Map(models.map(m => [m.slug, m]));
const unrunnableSlugs = new Set(unrunnable.map(u => u.model));

const res = await fetch('https://openrouter.ai/api/v1/models');
if (!res.ok) throw new Error(`OpenRouter catalog: HTTP ${res.status}`);
// '~' ids are OpenRouter's moving "latest" aliases
const catalog = new Map((await res.json()).data.filter(m => !m.id.startsWith('~')).map(m => [m.id, m]));

const tail = id => id.split('/').pop().toLowerCase();
const byTail = new Map();
for (const id of catalog.keys()) byTail.set(tail(id), [...(byTail.get(tail(id)) || []), id]);
const released = m => new Date(m.created * 1000).toISOString().slice(0, 10);
const perMillion = price => Number((Number(price) * 1e6).toPrecision(6));

function openrouterId(key, config) {
  if (ALIASES[key]) return catalog.has(ALIASES[key]) ? ALIASES[key] : null;
  const ids = new Set([...(byTail.get(key) || []), ...(byTail.get(tail(config.modelName)) || [])]);
  return ids.size === 1 ? [...ids][0] : null;
}

const out = {};
const keyOf = new Map();
for (const [key, config] of Object.entries(handWrittenModels)) {
  const id = openrouterId(key, config);
  if (!id) continue;
  keyOf.set(id, key);
  out[key] = { openrouter: id, released: released(catalog.get(id)) };
}

// A generated model older than its lab's current hand-written lineup is legacy
const lineupStart = {};
for (const [key, config] of Object.entries(handWrittenModels)) {
  const date = out[key]?.released;
  const lab = labOf({ ...config, ...out[key] });
  if (date && !config.legacy && !(lineupStart[lab] <= date)) lineupStart[lab] = date;
}

const skipped = [];
for (const slug of roster) {
  const m = meta.get(slug);
  if (m.not_run_after || unrunnableSlugs.has(slug)) continue;
  const panel = { panel: true, family: m.family, origin: m.origin, open: m.open, ...(m.provider && { pin: m.provider }) };
  const key = keyOf.get(slug) || (handWrittenModels[m.label] && m.label);
  if (key) {
    out[key] = { ...out[key], ...panel };
    continue;
  }
  const or = catalog.get(slug);
  if (m.host || !or) {
    skipped.push(`${slug}: ${m.host ? `served by ${m.host}; needs a hand-written entry` : 'not in the OpenRouter catalog'}`);
    continue;
  }
  out[m.label] = {
    provider: 'openrouter',
    modelName: slug,
    openrouter: slug,
    displayName: or.name.replace(/^[^:]+:\s*/, ''),
    ...(released(or) < lineupStart[labOf({ openrouter: slug })] && { legacy: true }),
    maxChars: or.context_length * CHARS_PER_TOKEN,
    cost: { input: perMillion(or.pricing.prompt), output: perMillion(or.pricing.completion) },
    released: released(or),
    ...panel,
  };
}

const today = new Date().toISOString().slice(0, 10);
writeFileSync(OUT, `// Generated by scripts/sync-panel.mjs on ${today} from modelun's consensus roster and the
// OpenRouter catalog. Do not edit; re-run the script.
export const panelModels = ${JSON.stringify(out, null, 2)};
`);

const count = pred => Object.values(out).filter(pred).length;
console.log(`${count(e => e.panel)} panel models (${count(e => e.panel && e.provider)} OpenRouter-only), ${count(e => e.openrouter)} with an OpenRouter route`);
if (skipped.length) console.log(`Skipped:\n  ${skipped.join('\n  ')}`);
